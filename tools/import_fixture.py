#!/usr/bin/env python3
"""Build games.js (the real draw) from the usaflnationals.app project's src/data.js.

Usage: python3 tools/import_fixture.py [/path/to/Nationals/app/src/data.js] > games.js

Reads TEAMS, GAMES and the boundary / timekeeping / scoring DUTY_GRID, and writes one entry
per game keyed day|time|field (e.g. "sat|9am|1"), the same keys the umpire schedule uses.
Slots the duty grid leaves empty, and all Grand Finals, are covered by the USAFL umpires.
"""
import json
import re
import sys

SRC = sys.argv[1] if len(sys.argv) > 1 else "/Users/alison/Desktop/Nationals/app/src/data.js"
DIV_CODE = {"m1": "MD1", "m2": "MD2", "m3": "MD3", "m4": "MD4", "m5": "MD5", "w": "WD1"}
UA = "USAFL umpires"


def q(x):
    """'abc' -> abc, null -> None"""
    x = x.strip()
    return None if x == "null" else x.strip("'\"")


def norm_time(t):
    """'9:00 AM' -> '9am', '4:30 PM' -> '4:30pm' (the umpire schedule's spelling)."""
    m = re.match(r"^\s*(\d{1,2}):(\d{2})\s*(AM|PM)\s*$", t, re.I)
    h, mm, ap = int(m.group(1)), m.group(2), m.group(3).lower()
    return f"{h}{'' if mm == '00' else ':' + mm}{ap}"


def main():
    src = open(SRC).read()

    teams = {}
    for m in re.finditer(r"^\s*T\(([^\n]*)\),\s*$", src, re.M):
        args = re.findall(r"'((?:[^'\\]|\\.)*)'|null", m.group(1))
        tid, div, _pool, code, name = args[0], args[1], args[2], args[3], args[4]
        teams[tid] = {"name": name.replace("\\'", "'"), "code": code}

    games = {}
    for m in re.finditer(r"^\s*G\((\d+),\s*'(\w+)',\s*'([^']+)',\s*(\d+),\s*'(\w+)',\s*([^,]+),\s*'([^']+)',\s*'([^']+)',\s*'([^']+)'\)", src, re.M):
        no, day, time, field, div, _pool, home, away, note = m.groups()
        games[int(no)] = {"no": int(no), "day": day, "time": norm_time(time), "field": int(field), "div": div,
                          "home": home, "away": away, "note": note}

    duty = {}
    grid = re.search(r"const DUTY_GRID = \{(.*?)\n\}", src, re.S).group(1)
    for day, rows in re.findall(r"(\w+): \[(.*?)\n  \]", grid, re.S):
        for row in re.findall(r"\[([^\]]+)\]", rows):
            cells = [q(c) for c in row.split(",")]
            for f, tid in enumerate(cells[1:], start=1):
                duty[(day, norm_time(cells[0]), f)] = tid

    def side(slot):
        """team id -> name/code; a seed ('W:n5', 'A1', '2') -> a readable placeholder."""
        if slot in teams:
            return teams[slot]["name"], teams[slot]["code"]
        m = re.match(r"^([WL]):n(\d+)$", slot)
        if m:
            g = games[int(m.group(2))]
            word = "Winner" if m.group(1) == "W" else "Loser"
            sf = re.match(r"Semi Final (\d)", g["note"])
            if sf:
                return f"{word} SF{sf.group(1)}", f"{word[0]}SF{sf.group(1)}"
            if g["home"] in teams and g["away"] in teams:
                pair = f"{teams[g['home']]['code']}/{teams[g['away']]['code']}"
                return f"{word} {pair}", f"{word[0]} {pair}"
            return f"{word} game {g['no']}", f"{word[0]}{g['no']}"
        m = re.match(r"^([AB])(\d)$", slot)
        if m:
            return f"Pool {m.group(1)} #{m.group(2)}", f"{m.group(1)}{m.group(2)}"
        if re.match(r"^\d$", slot):
            return {"1": "1st", "2": "2nd", "3": "3rd"}.get(slot, slot + "th") + " on ladder", "#" + slot
        return slot, slot

    out = {}
    for g in sorted(games.values(), key=lambda g: g["no"]):
        home, hcode = side(g["home"])
        away, acode = side(g["away"])
        tid = duty.get((g["day"], g["time"], g["field"]))
        club = teams[tid]["name"] if tid else UA
        if "Grand Final" in g["note"]:
            club = UA  # the UA does BTS for all Grand Finals
        out[f"{g['day']}|{g['time']}|{g['field']}"] = {
            "no": g["no"], "div": DIV_CODE[g["div"]], "round": g["note"],
            "home": home, "away": away, "homeCode": hcode, "awayCode": acode,
            "boundary": club, "timekeeper": club, "scorer": club,
        }

    print("// Game draw: teams, division and Boundary / Timekeeping / Scoring club, keyed day|time|field.")
    print("// Generated by tools/import_fixture.py from the usaflnationals.app fixture. Do not hand-edit.")
    print("window.GAMES = " + json.dumps({"placeholder": False, "games": out}, indent=1) + ";")
    print(f"{len(out)} games · {sum(1 for v in out.values() if v['boundary'] != UA)} with club duty", file=sys.stderr)


if __name__ == "__main__":
    main()
